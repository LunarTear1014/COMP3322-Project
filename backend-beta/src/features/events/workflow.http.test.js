import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { once } from "node:events";

const enabled = process.env.CLUBSPACE_TEST_DB === "1" && /^clubspace_test_/.test(process.env.DB_NAME || "");

test("HTTP request, independent approval, publish and versioned cancellation", { skip: !enabled }, async () => {
  const { default: pool } = await import("../../config/db.js");
  const { hash_password } = await import("../users/passwords.js");
  const suffix = `${Date.now()}-${Math.floor(Math.random() * 1000000)}`;
  const password = "local-http-test-password";
  const hash = await hash_password(password);
  const [organizer] = await pool.query("INSERT INTO users (email,password_hash,name,student_id) VALUES (?,?,?,?)", [`organizer-${suffix}@example.test`, hash, "Organizer", `o-${suffix}`]);
  const [admin] = await pool.query("INSERT INTO users (email,password_hash,name,student_id,platform_role) VALUES (?,?,?,?,'venue_admin')", [`admin-${suffix}@example.test`, hash, "Administrator", `a-${suffix}`]);
  const [club] = await pool.query("INSERT INTO clubs (name) VALUES (?)", [`HTTP Club ${suffix}`]);
  const [venue] = await pool.query("INSERT INTO venues (name,location,capacity) VALUES (?,?,?)", [`HTTP Venue ${suffix}`, "Test", 20]);
  await pool.query("INSERT INTO memberships (user_id,club_id,role) VALUES (?,?,'committee')", [organizer.insertId, club.insertId]);
  const port = 33318;
  const base = `http://127.0.0.1:${port}`;
  const launch = () => spawn(process.execPath, ["src/index.js"], { env: { ...process.env, PORT: String(port), APP_ORIGIN: base, SESSION_SECRET: "local-http-test-only" }, stdio: process.env.CLUBSPACE_TEST_DEBUG ? "inherit" : "ignore" });
  let child = launch();
  try {
    async function waitReady() {
      let ready = false;
      for (let i = 0; i < 100 && child.exitCode === null; i++) {
        try { if ((await fetch(`${base}/api/health`)).ok) { ready = true; break; } } catch { /* startup */ }
        await new Promise(resolve => setTimeout(resolve, 100));
      }
      assert.ok(ready, "test API did not start");
    }
    await waitReady();
    async function request(path, method = "GET", body, session, origin = base) {
      return fetch(`${base}${path}`, { method, headers: { ...(method !== "GET" ? { "Content-Type": "application/json", Origin: origin, "X-CSRF-Token": session?.token || "" } : {}), ...(session?.cookie ? { Cookie: session.cookie } : {}) }, ...(method !== "GET" ? { body: JSON.stringify(body ?? {}) } : {}) });
    }
    async function login(email) {
      const initial = await request("/api/v1/auth/csrf");
      const session = { cookie: initial.headers.get("set-cookie").split(";")[0], token: (await initial.json()).data.csrf_token };
      assert.equal((await request("/api/v1/auth/login", "POST", { email, password }, session, "http://wrong-origin.test")).status, 403);
      const response = await request("/api/v1/auth/login", "POST", { email, password }, session);
      assert.equal(response.status, 200);
      const newCookie = response.headers.get("set-cookie").split(";")[0];
      assert.notEqual(newCookie, session.cookie);
      const renewed = await request("/api/v1/auth/csrf", "GET", undefined, { cookie: newCookie });
      assert.equal(renewed.headers.get("set-cookie").split(";")[0], newCookie, "authenticated session cookie changed unexpectedly");
      const token = (await renewed.json()).data.csrf_token;
      assert.notEqual(token, session.token);
      return { cookie: newCookie, token };
    }
    const csrfResponse = await request('/api/v1/auth/csrf');
    const v1Anonymous = { cookie: csrfResponse.headers.get('set-cookie').split(';')[0], token: (await csrfResponse.json()).data.csrf_token };
    const badJson = await fetch(`${base}/api/v1/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base, Cookie: v1Anonymous.cookie, 'X-CSRF-Token': v1Anonymous.token }, body: '{' });
    assert.equal(badJson.status, 400);
    assert.equal((await badJson.json()).error.code, 'INVALID_JSON');
    const newEmail = `v1-${suffix}@example.test`;
    const registered = await request('/api/v1/auth/register', 'POST', { name: 'V1 Test', email: newEmail, student_id: `v1-${suffix}`, password }, v1Anonymous);
    assert.equal(registered.status, 201);
    assert.equal((await request('/api/v1/auth/session', 'GET', undefined, v1Anonymous)).status, 401);
    const v1Login = await request('/api/v1/auth/login', 'POST', { email: newEmail, password }, v1Anonymous);
    assert.equal(v1Login.status, 200);
    const v1LoginData = (await v1Login.json()).data;
    const v1Session = { cookie: v1Login.headers.get('set-cookie').split(';')[0], token: v1LoginData.csrf_token };
    assert.notEqual(v1Session.cookie, v1Anonymous.cookie);
    assert.notEqual(v1Session.token, v1Anonymous.token);
    assert.equal((await (await request('/api/v1/auth/session', 'GET', undefined, v1Session)).json()).data.user.email, newEmail);
    const profile = (await (await request('/api/v1/profile', 'GET', undefined, v1Session)).json()).data;
    assert.equal(profile.email, newEmail);
    assert.equal(Object.hasOwn(profile, 'password_hash'), false);
    assert.equal((await request('/api/v1/profile', 'PATCH', { platform_role: 'venue_admin' }, v1Session)).status, 422);
    assert.equal((await request('/api/v1/profile', 'PATCH', { email: `organizer-${suffix}@example.test` }, v1Session)).status, 409);
    const changedProfile = await request('/api/v1/profile', 'PATCH', { name: 'Updated Name' }, v1Session);
    assert.equal(changedProfile.status, 200);
    assert.equal((await changedProfile.json()).data.name, 'Updated Name');
    assert.equal((await (await request('/api/v1/profile', 'GET', undefined, v1Session)).json()).data.email, newEmail);
    assert.equal((await request('/api/v1/auth/logout', 'POST', {}, v1Session)).status, 204);
    assert.equal((await request('/api/v1/auth/session', 'GET', undefined, v1Session)).status, 401);
    const organizerCookie = await login(`organizer-${suffix}@example.test`);
    const adminCookie = await login(`admin-${suffix}@example.test`);
    assert.equal((await (await request("/api/v1/auth/csrf", "GET", undefined, organizerCookie)).json()).data.csrf_token, organizerCookie.token);
    assert.equal((await (await request("/api/v1/auth/csrf", "GET", undefined, adminCookie)).json()).data.csrf_token, adminCookie.token);
    const date = new Date(Date.now() + 10 * 86400000).toISOString().slice(0, 10);
    const v1Body = { club_id: club.insertId, venue_id: venue.insertId, title: 'Versioned event', description: 'Contract test', date,
      slot_id: 'afternoon', visibility: 'public', capacity: 10 };
    assert.equal((await request('/api/v1/events', 'POST', { ...v1Body, extra: true }, organizerCookie)).status, 422);
    const v1Create = await request('/api/v1/events', 'POST', v1Body, organizerCookie);
    assert.equal(v1Create.status, 201, await v1Create.clone().text());
    const v1Event = (await v1Create.json()).data;
    assert.equal(v1Event.state, 'draft');
    assert.equal(v1Event.booking.status, 'pending');
    assert.ok(v1Event.start_at.endsWith('Z'));
    const unrelatedCookie = await login(newEmail);
    const membershipPath = `/api/v1/clubs/${club.insertId}/membership`;
    const clubList = await request('/api/v1/clubs?page=1&page_size=100', 'GET', undefined, unrelatedCookie);
    assert.equal(clubList.status, 200);
    assert.ok((await clubList.json()).data.some(row => row.id === club.insertId && row.my_role === null));
    assert.equal((await request(membershipPath, 'PUT', {}, organizerCookie)).status, 200);
    assert.equal((await request(membershipPath, 'DELETE', {}, organizerCookie)).status, 409);
    const joinedClub = await request(membershipPath, 'PUT', {}, unrelatedCookie);
    assert.equal(joinedClub.status, 202, await joinedClub.clone().text());
    const joinRequest = (await joinedClub.json()).data;
    assert.equal(joinRequest.status, 'pending');
    assert.equal((await request(membershipPath, 'PUT', {}, unrelatedCookie)).status, 200);
    const requestListPath = `/api/v1/clubs/${club.insertId}/join-requests`;
    assert.equal((await request(requestListPath, 'GET', undefined, unrelatedCookie)).status,403);
    assert.ok((await (await request(requestListPath, 'GET', undefined, organizerCookie)).json()).data.some(row=>row.id===joinRequest.request_id));
    assert.equal((await request(`${requestListPath}/${joinRequest.request_id}/decision`, 'POST', { decision:'accept' }, unrelatedCookie)).status,403);
    assert.equal((await request(`${requestListPath}/${joinRequest.request_id}/decision`, 'POST', { decision:'accept' }, organizerCookie)).status,200);
    const memberships = await request('/api/v1/me/memberships?page=1&page_size=100', 'GET', undefined, unrelatedCookie);
    assert.ok((await memberships.json()).data.some(row => row.club_id === club.insertId && row.role === 'member'));
    assert.equal((await request(membershipPath, 'DELETE', {}, unrelatedCookie)).status, 204);
    assert.equal((await request(membershipPath, 'DELETE', {}, unrelatedCookie)).status, 204);
    const adminClubRequest = (await (await request(membershipPath,'PUT',{},adminCookie)).json()).data;
    assert.equal(adminClubRequest.status,'pending');
    assert.equal((await request(`${requestListPath}/${adminClubRequest.request_id}/decision`,'POST',{decision:'reject'},organizerCookie)).status,200);
    assert.equal((await (await request('/api/v1/me/memberships','GET',undefined,adminCookie)).json()).data.some(row=>row.club_id===club.insertId),false);
    await pool.query("INSERT INTO memberships (user_id,club_id,role) VALUES (?,?,'member'),(?,?,'member')",[v1LoginData.user.id,club.insertId,admin.insertId,club.insertId]);
    const privateDate = new Date(Date.parse(`${date}T00:00:00Z`)+2*86400000).toISOString().slice(0,10);
    const [privateBooking] = await pool.query("INSERT INTO bookings (venue_id,club_id,start_time,end_time,status) VALUES (?,?,?,?,'confirmed')",[venue.insertId,club.insertId,`${privateDate} 16:00:00`,`${privateDate} 18:00:00`]);
    const [privateEvent] = await pool.query("INSERT INTO events (booking_id,club_id,title,start_time,end_time,visibility,status,capacity) VALUES (?,?,?,?,?,'members_only','published',1)",[privateBooking.insertId,club.insertId,'Members request',`${privateDate} 16:00:00`,`${privateDate} 18:00:00`]);
    const privateJoin = `/api/v1/events/${privateEvent.insertId}/registration`;
    const requested = await request(privateJoin,'POST',{allow_waitlist:true},unrelatedCookie);
    assert.equal(requested.status,201,await requested.clone().text());
    assert.equal((await requested.json()).data.status,'pending');
    assert.equal((await (await request(`/api/v1/events/${privateEvent.insertId}`,'GET',undefined,unrelatedCookie)).json()).data.my_registration.status,'pending');
    const pendingRegistrations = await (await request('/api/v1/me/registrations?status=pending','GET',undefined,unrelatedCookie)).json();
    assert.ok(pendingRegistrations.data.some(row=>row.event.id===privateEvent.insertId && row.status==='pending'));
    const eventRequests = `/api/v1/events/${privateEvent.insertId}/join-requests`;
    assert.equal((await request(eventRequests,'GET',undefined,adminCookie)).status,403);
    assert.equal((await (await request(eventRequests,'GET',undefined,organizerCookie)).json()).data.length,1);
    assert.equal((await request(`${eventRequests}/${v1LoginData.user.id}/decision`,'POST',{decision:'accept'},adminCookie)).status,403);
    const accepted = await request(`${eventRequests}/${v1LoginData.user.id}/decision`,'POST',{decision:'accept'},organizerCookie);
    assert.equal(accepted.status,200,await accepted.clone().text());
    assert.equal((await accepted.json()).data.status,'joined');
    assert.equal((await request(privateJoin,'POST',{allow_waitlist:true},adminCookie)).status,201);
    const rejected = await request(`${eventRequests}/${admin.insertId}/decision`,'POST',{decision:'reject'},organizerCookie);
    assert.equal(rejected.status,200);
    assert.equal((await rejected.json()).data.status,'rejected');
    assert.equal((await request(privateJoin,'POST',{allow_waitlist:true},adminCookie)).status,201);
    const waitlisted = await request(`${eventRequests}/${admin.insertId}/decision`,'POST',{decision:'accept'},organizerCookie);
    assert.equal(waitlisted.status,200);
    assert.equal((await waitlisted.json()).data.status,'waitlisted');
    assert.equal((await request(privateJoin,'DELETE',{},unrelatedCookie)).status,200);
    assert.equal((await (await request(`/api/v1/events/${privateEvent.insertId}`,'GET',undefined,adminCookie)).json()).data.my_registration.status,'joined');
    assert.equal((await request(`/api/v1/events/${v1Event.id}`, 'GET', undefined, unrelatedCookie)).status, 404);
    assert.equal((await request(`/api/v1/events/${v1Event.id}`, 'PATCH', { expected_version: 1, title: 'Not allowed' }, unrelatedCookie)).status, 404);
    assert.equal((await request('/api/v1/me/events?club_id=' + club.insertId, 'GET', undefined, unrelatedCookie)).status, 403);
    const dayStart = `${date}T00:00:00Z`, dayEnd = new Date(Date.parse(dayStart)+86400000).toISOString();
    const calendarPath = `/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:dayStart,to:dayEnd})}`;
    const pendingCalendar = await request(calendarPath, 'GET', undefined, unrelatedCookie);
    assert.equal(pendingCalendar.status, 200);
    assert.equal((await pendingCalendar.json()).data.bookings.length, 0);
    const queueResponse = await request('/api/v1/bookings?status=pending&page=1&page_size=20', 'GET', undefined, adminCookie);
    assert.equal(queueResponse.status, 200);
    assert.ok((await queueResponse.json()).data.some(row => row.id === v1Event.booking.id));
    const approve = await request(`/api/v1/bookings/${v1Event.booking.id}/decision`, 'POST', { expected_version: v1Event.booking.version, decision: 'approve' }, adminCookie);
    assert.equal(approve.status, 200, await approve.clone().text());
    assert.equal((await approve.json()).data.status, 'confirmed');
    const privateCalendar = (await (await request(calendarPath, 'GET', undefined, unrelatedCookie)).json()).data;
    assert.equal(privateCalendar.bookings.length, 1);
    assert.deepEqual([privateCalendar.bookings[0].event_id,privateCalendar.bookings[0].title,privateCalendar.bookings[0].club_id],[null,null,null]);
    const versionedDraft = (await (await request(`/api/v1/events/${v1Event.id}`, 'GET', undefined, organizerCookie)).json()).data;
    assert.equal(versionedDraft.state, 'draft');
    const edited = await request(`/api/v1/events/${v1Event.id}`, 'PATCH', { expected_version: versionedDraft.version, title: 'Revised event' }, organizerCookie);
    assert.equal(edited.status, 200, await edited.clone().text());
    const revised = (await edited.json()).data;
    assert.equal(revised.title, 'Revised event');
    assert.equal((await request(`/api/v1/events/${v1Event.id}/publish`, 'POST', { expected_version: versionedDraft.version }, organizerCookie)).status, 409);
    assert.equal((await request(`/api/v1/events/${v1Event.id}/publish`, 'POST', { expected_version: revised.version }, organizerCookie)).status, 200);
    assert.equal((await (await request(calendarPath, 'GET', undefined, unrelatedCookie)).json()).data.bookings[0].event_id, v1Event.id);
    const beforeStart = new Date(Date.parse(v1Event.start_at)-3600000).toISOString();
    const adjacentPath = `/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:beforeStart,to:v1Event.start_at})}`;
    assert.equal((await (await request(adjacentPath,'GET',undefined,unrelatedCookie)).json()).data.bookings.length,0);
    const join = await request(`/api/v1/events/${v1Event.id}/registration`, 'POST', { allow_waitlist: true }, adminCookie);
    assert.equal(join.status, 201, await join.clone().text());
    assert.equal((await join.json()).data.status, 'joined');
    const mine = await request('/api/v1/me/registrations?status=joined&page=1&page_size=20', 'GET', undefined, adminCookie);
    assert.equal(mine.status, 200, await mine.clone().text());
    const mineEntry = (await mine.json()).data.find(row => row.event.id === v1Event.id);
    assert.ok(mineEntry.confirmed_at?.endsWith('Z'));
    assert.equal((await request(`/api/v1/events/${v1Event.id}/participants`, 'GET', undefined, adminCookie)).status, 403);
    const roster = await request(`/api/v1/events/${v1Event.id}/participants?status=joined`, 'GET', undefined, organizerCookie);
    assert.equal(roster.status, 200, await roster.clone().text());
    assert.equal((await roster.json()).data[0].user.id, admin.insertId);
    const from = new Date(Date.now()-86400000).toISOString(), to = new Date(Date.now()+12*86400000).toISOString();
    const reportPath = `/api/v1/clubs/${club.insertId}/reports?from=${encodeURIComponent(from)}&to=${encodeURIComponent(to)}`;
    assert.equal((await request(reportPath, 'GET', undefined, adminCookie)).status, 403);
    const v1Report = await request(reportPath, 'GET', undefined, organizerCookie);
    assert.equal(v1Report.status, 200, await v1Report.clone().text());
    assert.equal((await v1Report.json()).data.events.find(row => row.event_id === v1Event.id).joined_count, 1);
    const [[nextDay]] = await pool.query("SELECT DATE_FORMAT(DATE_ADD(?,INTERVAL 1 DAY),'%Y-%m-%d') AS day",[date]);
    const [overnightBooking] = await pool.query("INSERT INTO bookings (venue_id,club_id,start_time,end_time,status) VALUES (?,?,?,?,'confirmed')",[venue.insertId,club.insertId,`${date} 23:00:00`,`${nextDay.day} 01:00:00`]);
    const [overnightEvent] = await pool.query("INSERT INTO events (booking_id,club_id,title,start_time,end_time,capacity,status) VALUES (?,?,?,?,?,10,'published')",[overnightBooking.insertId,club.insertId,'Overnight',`${date} 23:00:00`,`${nextDay.day} 01:00:00`]);
    const overnightPath=`/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:`${date}T16:30:00Z`,to:`${date}T16:45:00Z`})}`;
    const overnight=(await (await request(overnightPath,'GET',undefined,unrelatedCookie)).json()).data.bookings;
    assert.ok(overnight.some(row=>row.event_id===overnightEvent.insertId && row.start_at===`${date}T15:00:00Z`));
    const tooLong=`/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:'2026-01-01T00:00:00Z',to:'2026-02-01T00:00:00.000001Z'})}`;
    assert.equal((await request(tooLong,'GET',undefined,unrelatedCookie)).status,422);
    const exactLimit=`/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:'2026-01-01T00:00:00Z',to:'2026-02-01T00:00:00Z'})}`;
    assert.equal((await request(exactLimit,'GET',undefined,unrelatedCookie)).status,200);
    const invalidDate=`/api/v1/venues/${venue.insertId}/calendar?${new URLSearchParams({from:'2026-02-30T00:00:00Z',to:'2026-03-02T00:00:00Z'})}`;
    assert.equal((await request(invalidDate,'GET',undefined,unrelatedCookie)).status,422);
    const found = await request('/api/v1/events?phase=upcoming&q=Revised&page_size=20', 'GET', undefined, adminCookie);
    assert.equal(found.status, 200);
    assert.ok((await found.json()).data.some(row => row.id === v1Event.id));
    const cancelV1 = await request(`/api/v1/events/${v1Event.id}/cancel`, 'POST', { expected_version: revised.version + 1, reason: 'Test cancellation' }, organizerCookie);
    assert.equal(cancelV1.status, 200, await cancelV1.clone().text());
    assert.equal((await cancelV1.json()).data.state, 'cancelled');
    for (const path of ['/api/events', '/api/venues', '/api/profile', '/api/auth/login', '/api/clubs/1/membership']) {
      const retired = await request(path, 'POST', {}, organizerCookie);
      assert.equal(retired.status, 410);
      assert.equal((await retired.json()).error.code, 'API_VERSION_RETIRED');
    }
    assert.equal((await request('/api/not-a-route')).status, 404);
    const unsupported = await request('/api/v1/auth/login');
    assert.equal(unsupported.status, 405);
    assert.equal(unsupported.headers.get('allow'), 'POST');
    assert.equal((await unsupported.json()).error.code, 'METHOD_NOT_ALLOWED');
    assert.equal((await request('/api/v1/profile', 'DELETE', {}, organizerCookie)).status, 405);
    assert.equal((await request(`/api/v1/clubs/${club.insertId}/membership`, 'GET', undefined, organizerCookie)).status, 405);
    child.kill("SIGTERM");
    await once(child, "exit");
    child = launch();
    await waitReady();
    assert.equal((await request("/api/v1/auth/session", "GET", undefined, organizerCookie)).status, 200);
    const invalidToken = { ...organizerCookie, token: "bad-token" };
    assert.equal((await request(`/api/v1/events/${v1Event.id}/cancel`, "POST", { expected_version: revised.version + 1, reason: "Test" }, invalidToken)).status, 403);
    for (let i = 0; i < 60; i++) {
      await pool.query("INSERT INTO notifications (user_id,event_id,event_title,message,type) VALUES (?,?,?,?,'event_changed')", [organizer.insertId, v1Event.id, 'Inbox test', `Notice ${i}`]);
    }
    const response = await request('/api/v1/notifications?page=2&page_size=20', 'GET', undefined, organizerCookie);
    const inbox = await response.json();
    assert.equal(response.status, 200);
    assert.ok(response.headers.get('x-request-id'));
    assert.equal(inbox.meta.total, 60);
    assert.equal(inbox.meta.unread_count, 60);
    assert.equal(inbox.data.length, 20);
    assert.equal(inbox.data[0].type, 'event_changed');
    assert.ok(inbox.data[0].created_at.endsWith('Z'));
    const noticeId = inbox.data[0].id;
    const foreign = await request(`/api/v1/notifications/${noticeId}/read`, 'PATCH', {}, adminCookie);
    assert.equal(foreign.status, 404);
    assert.equal((await foreign.json()).error.code, 'NOT_FOUND');
    const read = await (await request(`/api/v1/notifications/${noticeId}/read`, 'PATCH', {}, organizerCookie)).json();
    const again = await (await request(`/api/v1/notifications/${noticeId}/read`, 'PATCH', {}, organizerCookie)).json();
    assert.ok(read.data.read_at);
    assert.equal(again.data.read_at, read.data.read_at);
    const unread = await (await request('/api/v1/notifications?unread_only=true&page=1&page_size=1', 'GET', undefined, organizerCookie)).json();
    assert.equal(unread.meta.total, 59);
    assert.equal(unread.meta.unread_count, 59);
    assert.equal((await request('/api/v1/notifications?page=0', 'GET', undefined, organizerCookie)).status, 422);
    assert.equal((await request("/api/v1/auth/logout", "POST", {}, organizerCookie)).status, 204);
    assert.equal((await request("/api/v1/auth/session", "GET", undefined, organizerCookie)).status, 401);
  } finally {
    child.kill("SIGTERM");
    if (child.exitCode === null) await once(child, "exit");
    await pool.end();
  }
});
